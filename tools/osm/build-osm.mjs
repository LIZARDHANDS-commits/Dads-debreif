// Builds Traffic's roads and power lines from OpenStreetMap (TR-147; Patrick, 11 Oct: yes to "Roads from OpenStreetMap", "Power
// lines", with the credit line on screen). A one-time download over the pattern square (view3d.js PATTERN_MID_*, x -31,250 to
// 24,250 ft, y -35,450 to 20,050 ft from the ARP), turned into feet and written to src/modules/traffic/osm-features.js, so the
// tool fetches nothing while it runs. The data is OpenStreetMap's, © OpenStreetMap contributors, under the Open Database Licence
// (ODbL): the file keeps that notice and the 3D view shows the credit.
//
// Usage: node tools/osm/build-osm.mjs raw.json [--fetch]   (--fetch downloads raw.json first from the Overpass API)
import { readFileSync, writeFileSync } from 'node:fs';
import { makeLocalRef, latLonToLocalFt } from '../../src/core/geo.js';

const BBOX = '50.2331,-105.6934,50.3853,-105.4551'; // south, west, north, east: the pattern square
const QUERY = `[out:json][timeout:120];
(
  way["highway"~"^(motorway|trunk|primary|secondary|tertiary|unclassified|residential|track|motorway_link|trunk_link|primary_link|secondary_link|tertiary_link)$"](${BBOX});
  way["power"~"^(line|minor_line)$"](${BBOX});
);
out geom;`;

const [raw, flag] = process.argv.slice(2);
if (!raw) throw new Error('usage: node tools/osm/build-osm.mjs raw.json [--fetch]');
if (flag === '--fetch') {
  const res = await fetch('https://overpass-api.de/api/interpreter', {
    method: 'POST', body: new URLSearchParams({ data: QUERY }), headers: { 'User-Agent': 'DadsDebriefTool/1.0 (one-time map download)' },
  });
  writeFileSync(raw, await res.text());
}
const data = JSON.parse(readFileSync(raw, 'utf8'));
const ref = makeLocalRef(50.3303, -105.5592); // the ARP, as the 3D view's frame

/** Douglas-Peucker in feet: drops points within `tol` of the line. */
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  const L = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
  let worst = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs((b[0] - a[0]) * (a[1] - pts[i][1]) - (a[0] - pts[i][0]) * (b[1] - a[1])) / L;
    if (d > worst) { worst = d; at = i; }
  }
  if (worst <= tol) return [a, b];
  return [...simplify(pts.slice(0, at + 1), tol).slice(0, -1), ...simplify(pts.slice(at), tol)];
}

/** The surface a road is drawn with: 'highway' (paved, painted lines), 'paved', 'gravel' or 'dirt'. */
function surfaceOf(t) {
  const s = t.surface ?? '';
  const paved = /^(asphalt|paved|concrete)/.test(s);
  const loose = /^(gravel|unpaved|fine_gravel|compacted)/.test(s);
  const hw = t.highway.replace('_link', '');
  if (['motorway', 'trunk', 'primary', 'secondary'].includes(hw)) return loose ? 'gravel' : 'highway';
  if (hw === 'tertiary') return loose ? 'gravel' : 'paved';
  if (hw === 'residential') return loose ? 'gravel' : 'paved';
  if (hw === 'unclassified') return paved ? 'paved' : s === 'dirt' ? 'dirt' : 'gravel';
  return paved ? 'paved' : loose ? 'gravel' : 'dirt'; // track
}

const roads = [], power = [];
for (const e of data.elements) {
  if (e.type !== 'way' || !e.geometry) continue;
  const pts = simplify(e.geometry.map((g) => {
    const p = latLonToLocalFt(ref, g.lat, g.lon);
    return [Math.round(p.x), Math.round(p.y)];
  }), 3);
  const flat = pts.flat();
  const t = e.tags ?? {};
  if (t.highway) roads.push({ k: t.highway.replace('_link', ''), s: surfaceOf(t), p: flat });
  else if (t.power) power.push({ k: t.power === 'line' ? 'line' : 'minor', p: flat });
}
const out = `// GENERATED by tools/osm/build-osm.mjs from OpenStreetMap (TR-147). © OpenStreetMap contributors; the data is under the Open
// Database Licence (ODbL, opendatacommons.org/licenses/odbl). Downloaded ${data.osm3s?.timestamp_osm_base ?? 'unknown'} over the pattern square.
// Feet from the ARP (x east, y north), each line a flat list x0, y0, x1, y1, ...
// roads: k the road's class (primary, secondary, tertiary, residential, unclassified, track), s how it is drawn (highway, paved,
// gravel, dirt). power: k 'line' (transmission) or 'minor' (distribution), its points the poles OpenStreetMap has.
export const OSM_CREDIT = 'Roads and power lines © OpenStreetMap contributors';
export const OSM_ROADS = ${JSON.stringify(roads)};
export const OSM_POWER = ${JSON.stringify(power)};
`;
writeFileSync('src/modules/traffic/osm-features.js', out);
console.log(roads.length, 'roads', power.length, 'power lines', Math.round(out.length / 1024), 'KB');
